#!/usr/bin/env python3
"""Generate src/html-entities.ts from CPython's own `html` module.

The Crossref adapter renders JATS/HTML-marked metadata to plain text with the
same rules the project's Citation Resolver applies to the same Crossref fields
(`app/providers/common.py::clean_text`, which is `html.parser` + `html.unescape`
on CPython 3.13). Those rules depend on three tables that are data, not logic:
the WHATWG named character references, the numeric references HTML5 remaps, and
the code points it drops. This script copies them verbatim so the TypeScript
port never carries a hand-typed table.

    agentpkg/.venv/bin/python openclaw-agent-browser/scripts/generate-html-entities.py

The output is deterministic; re-running it on the same CPython produces the
same bytes, which `test/crossref.test.ts` pins with a digest.
"""

from __future__ import annotations

import html
import json
import sys
from html.entities import html5
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src" / "html-entities.ts"


def js(value: str) -> str:
    # ensure_ascii keeps the generated file 7-bit; the escapes are valid JS.
    return json.dumps(value, ensure_ascii=True)


def main() -> int:
    lines = [
        "/**",
        " * WHATWG character-reference tables, copied from CPython's `html` module.",
        " *",
        " * GENERATED by scripts/generate-html-entities.py from CPython "
        f"{sys.version_info.major}.{sys.version_info.minor}"
        " (`html.entities.html5`,",
        " * `html._invalid_charrefs`, `html._invalid_codepoints`). Do not edit by hand:",
        " * the Crossref adapter must render text exactly as the Citation Resolver does,",
        " * and a hand-edited table would be a second, silently different, source of truth.",
        " */",
        "/* eslint-disable */",
        "",
        "export const HTML5_ENTITIES: ReadonlyMap<string, string> = new Map<string, string>([",
    ]
    for name in sorted(html5):
        lines.append(f"  [{js(name)}, {js(html5[name])}],")
    lines.append("]);")
    lines.append("")
    lines.append(
        "export const INVALID_CHARREFS: ReadonlyMap<number, string> = new Map<number, string>(["
    )
    for number, text in sorted(html._invalid_charrefs.items()):
        lines.append(f"  [{number}, {js(text)}],")
    lines.append("]);")
    lines.append("")
    codepoints = sorted(html._invalid_codepoints)
    lines.append("export const INVALID_CODEPOINTS: ReadonlySet<number> = new Set<number>([")
    for start in range(0, len(codepoints), 12):
        chunk = ", ".join(str(value) for value in codepoints[start : start + 12])
        lines.append(f"  {chunk},")
    lines.append("]);")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(html5)} entities)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
