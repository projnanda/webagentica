@dataclass
class Response:
    status: int = 200
    headers: dict[str, str] = field(default_factory=dict)
    body: bytes = b""
    # Seconds to wait before the status line, or after the headers and a few bytes.
    delay: float = 0.0
    stall: float = 0.0


class _LocalConnection(http.client.HTTPConnection):
    """Reaches the fixture server while presenting the logical HTTPS host."""

    default_port = 443  # So the Host header reads exactly as an HTTPS request's does.

    def __init__(self, hostname: str, target: tuple[str, int], timeout: float):
        super().__init__(hostname, 443, timeout=timeout)
        self._target = target

    def connect(self):
        self.sock = socket.create_connection(self._target, self.timeout)


class FixtureWeb:
    def __init__(self):
        self.routes: dict[tuple[str, str], Response] = {}
        # Names a real resolver answers locally, answered the same way here.
        self.answers: dict[str, list[list[str]]] = {
            "localhost": [["127.0.0.1", "::1"]],
            "metadata.google.internal": [["169.254.169.254"]],
        }
        self.requests: list[dict] = []
        self.resolved: list[str] = []
        self.connections: list[tuple[str, str]] = []
        web = self

        class Handler(BaseHTTPRequestHandler):
            protocol_version = "HTTP/1.1"

            def do_GET(self):  # noqa: N802 - stdlib handler contract
                host = (self.headers.get("Host") or "").lower()
                headers = {name.lower(): value for name, value in self.headers.items()}
                web.requests.append({"host": host, "path": self.path, "headers": headers})
                response = web.routes.get((host, self.path)) or Response(
                    404, {"Content-Type": "text/plain"}, b"not found"
                )
                if response.delay:
                    time.sleep(response.delay)
                self.send_response(response.status)
                for name, value in response.headers.items():
                    self.send_header(name, value)
                if not any(
                    name.lower() in ("content-length", "transfer-encoding")
                    for name in response.headers
                ):
                    self.send_header("Content-Length", str(len(response.body)))
                self.end_headers()
                if response.stall:
                    self.wfile.write(response.body[:16])
                    self.wfile.flush()
                    time.sleep(response.stall)
                    return
                self.wfile.write(response.body)

            def log_message(self, *args):
                return

        self.server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
        self.server.daemon_threads = True
        # A refused transfer closes the socket mid-response on purpose; stay quiet.
        self.server.handle_error = lambda *args: None
        threading.Thread(
            target=self.server.serve_forever, kwargs={"poll_interval": 0.05}, daemon=True
        ).start()
        self.port = self.server.server_address[1]

    def close(self) -> None:
        self.server.shutdown()
        self.server.server_close()

    # -- what the web says ----------------------------------------------------
    def serve(
        self,
        url: str,
        body: bytes | str = b"",
        *,
        status: int = 200,
        content_type: str | None = HTML,
        headers: dict[str, str] | None = None,
        delay: float = 0.0,
        stall: float = 0.0,
    ) -> None:
        parts = urlsplit(url)
        target = (parts.path or "/") + (f"?{parts.query}" if parts.query else "")
        all_headers = {} if content_type is None else {"Content-Type": content_type}
        all_headers.update(headers or {})
        data = body.encode("utf-8") if isinstance(body, str) else body
        self.routes[(parts.hostname, target)] = Response(status, all_headers, data, delay, stall)

    def redirect(self, url: str, location: str, *, status: int = 302, **extra) -> None:
        headers = {"Location": location, **extra.pop("headers", {})}
        self.serve(url, status=status, content_type=None, headers=headers, **extra)

    def answer(self, hostname: str, *answers: list[str]) -> None:
        """DNS answers for `hostname`, one list per lookup; the last one repeats."""
        self.answers[hostname] = [list(addresses) for addresses in answers]

    # -- the seams ------------------------------------------------------------
    def resolver(self, hostname, port, **kwargs):
        self.resolved.append(hostname)
        try:
            ipaddress.ip_address(hostname)
            addresses = [hostname]
        except ValueError:
            queue = self.answers.get(hostname)
            if queue is None:
                addresses = [PUBLIC]
            else:
                addresses = queue.pop(0) if len(queue) > 1 else queue[0]
        if not addresses:
            raise socket.gaierror("fixture: no such host")
        answers = []
        for item in addresses:
            family = socket.AF_INET6 if ":" in item else socket.AF_INET
            answers.append((family, socket.SOCK_STREAM, 6, "", (item, port)))
        return answers

    def connector(self, hostname, address, timeout):
        self.connections.append((hostname, address))
        connection = _LocalConnection(hostname, ("127.0.0.1", self.port), timeout)
        connection.connect()
        return connection

    @property
    def network(self) -> DiscoveryNetwork:
        return DiscoveryNetwork(resolver=self.resolver, connector=self.connector)

    def package_transport(self, url, limits) -> bytes:
        """The control plane's download seam, through the production package policy."""
        return fetch_https_package(
            url, limits=limits, resolver=self.resolver, connector=self.connector
        )

    def paths(self, host: str | None = None) -> list[str]:
        return [item["path"] for item in self.requests if host is None or item["host"] == host]


def page(head: str = "", body: str = "<p>Hello.</p>") -> str:
    """A small, ordinary HTML document."""
    return (
        "<!doctype html>\n<html lang=en>\n<head>\n<meta charset=utf-8>\n<title>Example</title>\n"
        f"{head}\n</head>\n<body>\n{body}\n</body>\n</html>\n"
    )


def link(href: str = "/agent.pkg", *, rel: str = "agent-package", type_: str | None = None) -> str:
    kind = f' type="{type_}"' if type_ is not None else ""
    return f'<link rel="{rel}"{kind} href="{href}">'


def resigned_webair(directory: Path) -> bytes:
    """WebAir's own source, built and validly signed by a key nobody pinned."""
    source = directory / "webair-src"
    shutil.copytree(ROOT / "agents/webair", source)
    artifact = build_package(source, directory / "copy.agent.pkg")
    keygen(directory / "stranger.pem", directory / "stranger.pub.pem")
    signed = sign_package(artifact, directory / "stranger.pem", directory / "signed.agent.pkg")
    return signed.read_bytes()


def tampered_webair() -> bytes:
    """The real signed WebAir archive with one skill changed and its integrity rehashed."""
    package = load_package(WEBAIR_ARCHIVE)
    files = dict(package.files)
    skill = next(name for name in sorted(files) if name.startswith("skills/"))
    files[skill] = b"# Changed after signing, integrity statement recomputed.\n"
    return archive_bytes(files, package.signature)


def publish_webair(
    web: FixtureWeb, origin: str = "https://webair.example", archive: bytes | None = None
) -> None:
    """WebAir's own pages, and its signed package (or other bytes) at its package path."""
    for item in WEBAIR_SITE["pages"]:
        web.serve(origin + item["path"], item["html"], content_type=item["content_type"])
    web.serve(
        origin + WEBAIR_SITE["agent_package"]["path"],
        WEBAIR_ARCHIVE.read_bytes() if archive is None else archive,
        content_type=PACKAGE_MEDIA_TYPE,
    )
