"""A deterministic stand-in for the public web, reached only through the fetch seams.

`FixtureWeb` gives synthetic public origins (`https://webair.example`, ...) canned
responses from one local plaintext server. Its resolver answers each name with the
addresses a test chose (one public address by default, and an IP literal as itself, as
`getaddrinfo` does), and its connector connects to that server while keeping the logical
hostname. Only DNS and socket mechanics are replaced: the Host header, URL policy,
address classification, redirects, content handling and parsing under test are the
production code. TLS pinning itself is covered against real hosts only, as in
`test_browser_fetch.py`. Nothing here contacts a network.

`publish_webair` serves WebAir's own pages, as its origin renders them
(`examples/webair-site.json`, generated by `demo/webair/publisher`), and its real signed
package (`dist/webair-0.1.0.agent.pkg`).
"""

