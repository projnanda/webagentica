"""The signed WebAir demo packages, as the generic runtime sees them.

WebAir is a fictional airline origin (`demo/webair/`) that publishes this package next to
its HTML. These tests pin the shipped artifacts and show they are ordinary workflow.v0
packages: they verify with the standard tooling, run through the unchanged CLI, conversation
runner and interpreter with the package's own fixture, ask for nothing they do not declare,
and no generic code knows they exist.

0.8.0 is the current package: 0.7.0 as a conversation (conversation.v0, T24): one message per
turn, a declared persistent state (the history, the known fares, the open quote and the
confirmation as summaries), and a consent step before the simulated purchase, which the
`once`-grantable purchase authority still covers. 0.7.0 checked WebAir's fare totals in a
WebAssembly module (compute.v0, T22); 0.6.0 read the travel profile from the person's memory
and added the `remember` step (memory.v0, T20); 0.5.0 answered a request without a departure
airport; 0.4.0 added the profiles; 0.3.0 was the live demo's package. Every version since
0.2.0 asks the person's host for a passenger identity and a payment method it does not own
(`personal.read` with argument-free host-resource tools). These tests also pin what that
means for the signed bytes: no name, email, host resource id or label is in them. That the
host resolves, binds and withholds those resources correctly is tested on the host side
(`openclaw-agent-browser/test/webair-capabilities.test.ts` on 0.5.0, the Chrome suite on the
current one); that the tool contracts equal WebAir's published API is tested on the origin
side (`demo/webair/tests/`).

0.1.0 to 0.7.0 stay here unchanged and verifiable: earlier evidence describes those exact bytes.
"""

