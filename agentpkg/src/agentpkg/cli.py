def _browser(args):
    """Control-plane commands. No package is executed by any of them."""
    from .browser import (
        BrowserPolicy,
        BrowserService,
        ControlPlane,
        ControlPlaneConfig,
        TrustStore,
        default_cache_dir,
        default_trust_store,
    )
    from .browser.trust import read_public_key_file

    store_path = Path(args.trust_store) if args.trust_store else default_trust_store()
    if args.command == "trust":
        store = TrustStore(store_path)
        if args.action == "list":
            return {
                "trust_store": store.state(),
                "publishers": [entry.as_json() for entry in store.entries()],
            }
        if args.action == "add":
            if not args.public_key or not args.display_name:
                raise AgentPkgError("trust add requires --public-key and --display-name")
            entry = store.add(
                read_public_key_file(args.public_key),
                display_name=args.display_name,
                publisher_id=args.publisher_id,
                package_id_prefix=args.package_id_prefix,
                notes=args.note,
                replace=args.replace,
            )
            return {"added": entry.as_json(), "trust_store": store.state()}
        if not args.fingerprint:
            raise AgentPkgError("trust remove requires --fingerprint sha256:<hex>")
        entry = store.remove(args.fingerprint)
        return {"removed": entry.as_json(), "trust_store": store.state()}

    config = ControlPlaneConfig(
        cache_dir=Path(args.cache_dir) if args.cache_dir else default_cache_dir(),
        trust_store_path=store_path,
        session_ttl_seconds=args.session_ttl,
        max_sessions=args.max_sessions,
        policy=BrowserPolicy(
            require_valid_signature=not args.allow_unsigned,
            require_trusted_publisher=not args.allow_untrusted_publisher,
            require_confirmed_model_compatibility=not args.allow_unverified_model,
        ),
    )
    if args.quiet and not (args.token_file or args.token):
        # A supervising host must still be able to obtain the token out of band.
        raise AgentPkgError("--quiet requires --token-file (or an explicit --token)")
    service = BrowserService(
        ControlPlane(config), host=args.host, port=args.port, token=args.token, quiet=args.quiet
    )
    if args.token_file:
        write_new(args.token_file, (service.token + "\n").encode(), mode=0o600)
    startup = {
        "service": "agentpkg-browser-control-plane",
        "status": "listening",
        "url": service.url,
        "api_version": "v0",
        **({} if args.quiet else {"token": service.token}),
        "token_file": args.token_file,
        "cache_dir": str(service.control.cache_dir),
        "trust_store": str(store_path),
        "execution": "disabled",
        "hint": f"curl -sS {service.url}/v0/health",
    }
    if args.quiet:
        # One compact line, so a supervising host can parse readiness without
        # buffering an indented document.
        print(json.dumps(startup, ensure_ascii=False, allow_nan=False), flush=True)
    else:
        _print(startup)

    def stop(*_):
        raise KeyboardInterrupt

    try:
        # A terminated service should still purge its snapshots; a hard kill is
        # covered by the next start's stale-snapshot sweep.
        signal.signal(signal.SIGTERM, stop)
    except ValueError:
        pass
    try:
        service.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        service.shutdown()
        service.server_close()
    return {"service": "agentpkg-browser-control-plane", "status": "stopped"}


def _dispatch(args):
    command = args.command
    if command == "build":
        path = build_package(args.source, args.output)
        return {"artifact": str(path), "digest": load_package(path).digest}
    if command == "keygen":
        return keygen(args.private_key, args.public_key)
    if command == "sign":
        path = sign_package(args.package, args.private_key, args.output)
        return {
            "artifact": str(path),
            "signed": True,
            "digest": load_package(path).digest,
            "trust": "Verify using a separately pinned publisher public key",
        }
    if command == "verify":
        return verify_package(args.package, trusted_key=args.trust_key)
    if command == "unpack":
        return {
            "source": str(unpack_package(args.package, args.output)),
            "signature_preserved": False,
        }
    if command in ("browser-serve", "trust"):
        return _browser(args)
    if command == "host-bridge":
        # stdout belongs to the protocol from here on: this returns the process
        # exit status directly and prints nothing.
        from .hostbridge import serve

        return _Exit(asyncio.run(serve()))
    if command == "execution-run":
        # The runner. stdout is the protocol; the package and the artifact
        # directory arrive as inherited descriptors, so no path is named here.
        from .execution import serve as serve_execution

        return _Exit(asyncio.run(serve_execution()))
    if command == "host-pdf-read":
        # A trusted host capability, not a package operation: bytes arrive on
        # stdin from the broker that holds the person's selection, and the
        # answer is the only thing written to stdout.
        from .hostfiles import serve_stdin

        return _Exit(serve_stdin())
    if command == "install-openclaw":
        from .openclaw import stage_openclaw

        return stage_openclaw(args.package, args.workspace, trusted_key_path=args.trust_key)
    package = load_package(args.package)
    if command == "validate":
        return {
            "valid": True,
            "package_id": package.manifest["package_id"],
            "version": package.manifest["version"],
            "digest": package.digest,
            "signature_present": package.signature is not None,
            "publisher_trust": "not checked; use verify --trust-key",
        }
    if command == "inspect":
        return inspect_package(package)
    if command == "permissions":
        return permissions_summary(package)
    if command == "converse":
        return _converse(args, package)
    if command in ("run", "eval"):
        from .fixtures import fixture_adapters
        from .workflow import run_workflow

        if package.manifest["entrypoint"] != "workflow.v0":
            raise AgentPkgError(
                "Generic execution requires workflow.v0; use agentpkg-legacy "
                "for the archived development profile"
            )
        if package.graph.get("conversation") is not None:
            # conversation.v0: a turn starts from a persisted state a single run does not have.
            raise AgentPkgError(
                "conversation_profile: this package declares a conversation and runs turn by "
                "turn; use agentpkg converse"
            )
        mode = args.mode if command == "run" else "fixture"
        if mode == "live" and not args.trust_key:
            raise AgentPkgError("Live run requires a signed artifact and --trust-key PUBLIC_KEY")
        if command == "run" and args.trust_key:
            verified = verify_package(args.package, trusted_key=args.trust_key)
            if verified["digest"] != package.digest:
                raise AgentPkgError("Package changed between loading and signature verification")
        if mode == "fixture":
            router, handlers, input_value = fixture_adapters(package)
        else:
            from .models import HTTPRouter
            from .tools import create_handlers

            if not args.router_config or not args.input:
                raise AgentPkgError("Live workflow execution requires --router-config and --input")
            router = HTTPRouter.from_config(args.router_config)
            handlers = create_handlers(
                package,
                selected_files=(_json_file(args.selected_files) if args.selected_files else None),
                resolver_base_url=args.resolver_base_url,
            )
            input_value = _json_file(args.input, None)
        grants = (
            _json_file(args.grants)
            if command == "run"
            else {p["id"]: "session" for p in package.policy["permissions"]}
        )
        if command == "run" and args.input:
            input_value = _json_file(args.input, None)
        # The operator is the host here. `run` requires each tool to be named,
        # because approving a tool is a separate decision from granting the
        # permission it travels under. `eval` runs the package's own declared
        # fixtures under blanket consent, which is already what its grants say.
        approved = (
            sorted(set(args.approve_tool or ())) if command == "run" else sorted(package.tools)
        )
        unknown = sorted(set(approved) - set(package.tools))
        if unknown:
            raise AgentPkgError(
                f"--approve-tool names tools this package does not declare: {unknown}"
            )
        # memory.v0 (agentpkg 0.4.0): the run's memory from --memory-dir, or in fixture mode from
        # the package's own replayed answers (M-62, M-63, D-230).
        from .memory.host import cli_memory

        memory_run, _folder, memory_handlers = cli_memory(
            package,
            mode=mode,
            decisions=grants,
            memory_dir=getattr(args, "memory_dir", None),
            memory_grants=getattr(args, "memory_grant", None) or (),
        )
        if mode == "live":
            handlers = {**handlers, **memory_handlers}
        options = dict(
            grants=grants,
            handlers=handlers,
            router=router,
            approved_tools=approved,
            memory=memory_run,
        )
        if command == "run" and args.limits:
            options["limits"] = _json_file(args.limits)
        if args.out:
            if (
                Path(args.out).exists()
                or Path(args.out).is_symlink()
                or not Path(args.out).parent.is_dir()
            ):
                raise ValidationError("--out must name a new directory under an existing parent")
            import os

            parent_fd, _ = _open_parent(args.out)
            os.close(parent_fd)
        try:
            result = asyncio.run(run_workflow(package, input_value, **options))
        except Exception as exc:
            report = getattr(exc, "execution_report", None)
            if report is not None and args.out:
                _write_result(args.out, report)
            raise
        if args.out:
            _write_result(args.out, result, package)
        if memory_run.commit_error:
            # M-50: the folder refused the agent document; the Run Record says `store_failed`.
            print(
                f"agentpkg: the agent document was not committed: {memory_run.commit_error}",
                file=sys.stderr,
            )
        return {
            "status": result["status"],
            "profile": "workflow.v0",
            "output_directory": args.out,
            "usage": result["usage"],
            "approved_tools": approved,
            "fixture_replay": mode == "fixture",
            "passed": result["status"] == "completed",
        }
    raise AgentPkgError(f"Unsupported command: {command}")


def _converse(args, package):
    """`agentpkg converse`: one conversation of a conversation.v0 package from a transcript.

    The host here is the operator: the grants are the plan's decisions for the whole conversation,
    the transcript's consent decisions stand for the person's, and each turn's adapters are the
    ones `run` would build (fixture replay, or the live router and handlers over the same memory
    folder). Every turn's artifacts go to `turn-NNN/` under `--out` as the turn ends; the
    conversation's transcript, state, one audit chain, usage and provenance are written last.
    """
    from .artifacts import artifact_records, write_artifacts
    from .conversation import Conversation
    from .conversation.transcript import check_transcript, read_input_transcript
    from .fixtures import fixture_adapters
    from .memory.host import cli_memory
    from .package import create_directory

    if package.graph.get("conversation") is None:
        raise AgentPkgError(
            "conversation_profile_required: this package declares no conversation; use agentpkg run"
        )
    mode = args.mode
    if mode == "live" and not args.trust_key:
        raise AgentPkgError("Live run requires a signed artifact and --trust-key PUBLIC_KEY")
    if args.trust_key:
        verified = verify_package(args.package, trusted_key=args.trust_key)
        if verified["digest"] != package.digest:
            raise AgentPkgError("Package changed between loading and signature verification")
    if args.transcript:
        transcript = read_input_transcript(args.transcript)
    elif mode == "fixture" and package.graph["conversation"].get("fixture"):
        transcript = package.json(package.graph["conversation"]["fixture"])
    else:
        raise AgentPkgError(
            "A conversation needs --transcript (in fixture mode the package's conversation "
            "fixture serves when it declares one)"
        )
    grants = _json_file(args.grants)
    # An approval of an undeclared tool is refused by the conversation's own check (T23 review 2).
    approved = sorted(set(args.approve_tool or ()))
    check_transcript(transcript, package, grants)
    if mode == "fixture":
        router, handlers, _ = fixture_adapters(package)
    else:
        from .models import HTTPRouter
        from .tools import create_handlers

        if not args.router_config:
            raise AgentPkgError("Live conversation requires --router-config")
        router = HTTPRouter.from_config(args.router_config)
        handlers = create_handlers(
            package,
            selected_files=(_json_file(args.selected_files) if args.selected_files else None),
            resolver_base_url=args.resolver_base_url,
        )

    memory_runs = {}

    def memory_for_turn():
        # A fresh memory run per turn over the same folder (M-50 per turn, V-26).
        return cli_memory(
            package,
            mode=mode,
            decisions=grants,
            memory_dir=args.memory_dir,
            memory_grants=args.memory_grant or (),
        )

    # The memory inputs (the folder, `--memory-grant`) are resolved for the first turn before
    # `--out` exists, so a refused folder or grant leaves no half-made directory behind (T23
    # review 2, nit 1); later turns resolve their own run over the same folder.
    first_memory = memory_for_turn()

    def adapters(turn):
        memory_run, _folder, memory_handlers = first_memory if turn == 1 else memory_for_turn()
        memory_runs[turn] = memory_run
        return {
            "router": router,
            "handlers": {**handlers, **memory_handlers} if mode == "live" else handlers,
            "memory": memory_run,
        }

    out = Path(args.out)
    if out.exists() or out.is_symlink() or not out.parent.is_dir():
        raise ValidationError("--out must name a new directory under an existing parent")

    def on_turn(index, report, status):
        records = artifact_records(report, package if status == "completed" else None)
        write_artifacts(out / f"turn-{index:03d}", records)
        memory_run = memory_runs.pop(index, None)
        if memory_run is not None and memory_run.commit_error:
            # M-50 per turn: the folder refused the agent document; the turn's Run Record says
            # `store_failed`, as `run` reports it for a run.
            print(
                f"agentpkg: turn {index}: the agent document was not committed: "
                f"{memory_run.commit_error}",
                file=sys.stderr,
            )

    # The conversation checks the grants, the approvals and the limits before anything is
    # written, so a refused host input leaves no half-made --out behind.
    conversation = Conversation(
        package,
        grants=grants,
        approved_tools=approved,
        adapters=adapters,
        limits=_json_file(args.limits) if args.limits else None,
        on_turn=on_turn,
    )
    create_directory(out)
    result = asyncio.run(conversation.run(transcript))
    for name, value in (
        ("transcript.json", result["transcript"]),
        ("state.json", result["state"]),
        ("audit.json", result["audit"]),
        ("usage.json", result["usage"]),
        ("provenance.json", result["provenance"]),
    ):
        data = (json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + "\n").encode()
        write_new(out / name, data, mode=0o600)
    return {
        "status": result["status"],
        "profile": "conversation.v0",
        "conversation_id": result["provenance"]["conversation_id"],
        "output_directory": args.out,
        "turns": [
            {"turn": t["turn"], "status": t["status"]} for t in result["transcript"]["turns"]
        ],
        "ended": result["ended"],
        "usage": {
            key: result["usage"][key] for key in ("turns", "tokens", "remote_calls", "tool_calls")
        },
        "approved_tools": approved,
        "fixture_replay": mode == "fixture",
        "passed": result["status"] == "completed",
    }


def main(argv=None):
    args = parser().parse_args(argv)
    try:
        result = _dispatch(args)
        if isinstance(result, _Exit):
            return int(result)
        _print(result)
        if args.command in ("eval", "converse") and result.get("passed") is False:
            return 1
        return 0
    except (AgentPkgError, OSError, ValueError) as exc:
        print(f"agentpkg: {exc}", file=sys.stderr)
        return 2
