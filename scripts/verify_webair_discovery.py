def multiple(call: _Client) -> dict:
    result = discover(call, "https://multi.example/")[1]
    report = {
        "website": "https://multi.example/",
        "status": result["discovery_status"],
        "advertised": [item["resolved_url"] for item in result["candidates"]],
        "chosen": None,
        "sessions": sessions(call),
    }
    report["passed"] = report["status"] == "multiple_candidates" and report["sessions"] == 0
    return report


def policy(call: _Client, web: FixtureWeb) -> dict:
    refused = {}
    for url in (
        "http://webair.example/",
        "http://127.0.0.1:8040/",
        "https://127.0.0.1/",
        "https://localhost/",
        "https://[::1]/",
        "https://10.0.0.5/",
        "https://169.254.169.254/latest/meta-data/",
        "https://user:secret@webair.example/",
        "https://webair.example:8443/",
        "https://moved.example/",
        f"{WEBAIR}/agent.pkg",
    ):
        status, body = discover(call, url)
        refused[url] = {"http_status": status, "code": body["error"]["code"]}
    contacted = sorted({host for host, _ in web.connections})
    return {
        "refused": refused,
        "hosts_ever_connected": contacted,
        "passed": all(item["http_status"] >= 400 for item in refused.values())
        and refused["http://127.0.0.1:8040/"]["code"] == "url_rejected"
        and refused["https://127.0.0.1/"]["code"] == "url_destination_denied"
        and refused["https://moved.example/"]["code"] == "discovery_redirect_refused"
        and refused[f"{WEBAIR}/agent.pkg"]["code"] == "discovery_not_html"
        and not any(host in contacted for host in ("127.0.0.1", "localhost", "::1", "10.0.0.5")),
    }


def genericity() -> dict:
    hits = []
    for base, suffixes in (
        (ROOT / "agentpkg/src/agentpkg/browser", {".py"}),
        (ROOT / "openclaw-agent-browser/src", {".ts", ".css"}),
    ):
        for path in sorted(base.rglob("*")):
            if path.is_file() and path.suffix in suffixes:
                text = path.read_text(errors="replace").lower()
                # A package id is `org.webagents.<name>`; the extension namespace
                # `org.webagents:<extension>` (profiles-v0, read generically) is not one (T9).
                if "webair" in text or "org.webagents." in text:
                    hits.append(path.relative_to(ROOT).as_posix())
    return {"files_mentioning_webair_or_a_package_id": hits, "clean": not hits}


def verify() -> dict:
    with tempfile.TemporaryDirectory(prefix="webair-discovery-") as directory:
        scratch = Path(directory).resolve()
        web = FixtureWeb()
        publish(web, scratch)
        control = ControlPlane(
            ControlPlaneConfig(
                cache_dir=scratch / "cache", trust_store_path=scratch / "trust.json"
            ),
            transport=web.package_transport,
            discovery_network=web.network,
        )
        service = BrowserService(control, host="127.0.0.1", port=0)
        service.start_background()
        call = _Client(service)
        try:
            scenarios = {
                "A_webair": scenario_a(call, web),
                "B_no_agent": scenario_b(call),
                "C_cross_origin_advertisement": scenario_c(call, web),
                "D_invalid_package": scenario_d(call),
                "E_valid_signature_untrusted_signer": scenario_e(call),
            }
            others = {
                "second_origin": second_origin(call),
                "multiple_candidates": multiple(call),
                "policy": policy(call, web),
            }
            capabilities = call("GET", "/v0/status")[1]["capabilities"]
        finally:
            service.shutdown()
            service.server_close()
            web.close()
    generic = genericity()
    checks = {
        **{f"scenario_{name}": item["passed"] for name, item in scenarios.items()},
        **{name: item["passed"] for name, item in others.items()},
        "control_plane_executes_nothing": capabilities["execute"] is False,
        "no_site_or_package_name_in_generic_code": generic["clean"],
    }
    return {
        "passed": all(checks.values()),
        "checks": checks,
        "convention": {
            "element": '<link rel="agent-package" type="application/vnd.webagents.agent-package"'
            ' href="...">',
            "rel": "agent-package",
            "media_type": PACKAGE_MEDIA_TYPE,
            "status": "experimental WebAgents metadata; not a registered link relation or media "
            "type and not a web standard",
            "conveys": "a location only: no identity, integrity, trust, permission or authority",
            "profile": "same-origin-v0: document head only, same-origin candidates only, at most "
            "5 same-origin redirects, 1 MiB",
        },
        "fixture": {
            "web": "agentpkg/tests/web_fixtures.py: synthetic public origins served by one local "
            "server; only DNS answers and socket connections are replaced",
            "webair_pages": {
                "source": "examples/webair-site.json",
                "generated_by": "demo/webair/publisher (python -m publisher sync|check)",
                "pages": {
                    item["path"]: sha256(item["html"].encode("utf-8"))
                    for item in WEBAIR_SITE["pages"]
                },
            },
            "webair_package": {
                "path": "dist/webair-0.1.0.agent.pkg",
                "archive_sha256": sha256(WEBAIR_ARCHIVE.read_bytes()),
                "digest": WEBAIR_DIGEST,
            },
            "trust_store": "empty; scenario A pins WebAir's public key explicitly through the "
            "operator API and removes it again",
        },
        "scenarios": scenarios,
        **others,
        "genericity": generic,
        "scope": "offline: the production control plane over its HTTP API, its discovery and "
        "package paths, against a fixture web; no real network, origin server, model, OpenClaw "
        "host or Agent Browser page. The page's behaviour is covered by the plugin's tests.",
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--report", help="Optional new JSON report file; refuses overwrites")
    args = parser.parse_args()
    report = verify()
    encoded = (json.dumps(report, indent=2, ensure_ascii=False) + "\n").encode()
    if args.report:
        write_new(args.report, encoded)
    print(encoded.decode(), end="")
    return 0 if report["passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
