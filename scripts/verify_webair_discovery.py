"""Offline acceptance of website discovery, with WebAir as the website.

    agentpkg/.venv/bin/python scripts/verify_webair_discovery.py [--report PATH]

Starts the production control plane (`BrowserService` over `ControlPlane`) on loopback and
drives it over its HTTP API, as the Agent Browser does. Its network is a fixture web
(`agentpkg/tests/web_fixtures.py`) that replaces only DNS and sockets: WebAir's own pages,
as its origin renders them (`examples/webair-site.json`, generated by `demo/webair/publisher`),
its real signed package (`dist/webair-0.1.0.agent.pkg`), and other synthetic origins. Every URL
policy, parser, verifier and trust decision is production code. Nothing contacts a real
network, an origin server, a model or the Agent Browser UI.

Five scenarios: A, WebAir's page leads to its package, which verifies and reaches the normal
trust and authorization flow; B, an ordinary site advertises nothing; C, a cross-origin
advertisement is rejected and never fetched; D, a valid advertisement of an invalid or tampered
package fails inspection normally; E, a valid signature by an unknown key stays untrusted.

Prints a JSON report; `passed` is false if any check fails. The report holds no timestamp,
session id or random key material, so a rerun reproduces it.
"""

from __future__ import annotations

