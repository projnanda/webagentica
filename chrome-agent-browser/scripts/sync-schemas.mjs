#!/usr/bin/env node
/**
 * Copy agentpkg's JSON Schemas into the core (D-025).
 *
 * `agentpkg/src/agentpkg/schemas/*.json` is the single source. This script copies every
 * schema byte for byte into `src/core/schemas/` and writes `src/core/schemas/index.ts`,
 * which imports them as JSON modules so the bundle needs no file access at runtime.
 * `test/core/schemas.test.ts` asserts the copies equal the originals, so a schema change
 * that is not re-synced fails the suite instead of drifting.
 *
 * Extension schemas (D-040) live beside the specs, not under agentpkg, which ignores them:
 * `spec/extensions/*.schema.json` is copied the same way into `src/core/schemas/extensions/`.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const project = resolve(here, "..");
const source = resolve(project, "..", "agentpkg", "src", "agentpkg", "schemas");
const target = resolve(project, "src", "core", "schemas");

mkdirSync(target, { recursive: true });
const names = readdirSync(source)
  .filter((name) => name.endsWith(".schema.json"))
  .sort();
if (names.length === 0) throw new Error(`no schemas found under ${source}`);

for (const name of names) {
  writeFileSync(join(target, name), readFileSync(join(source, name)));
}

// A `Schema` suffix keeps every binding clear of reserved words: `eval.schema.json` would
// otherwise import as `eval`, which a bundler accepts and Node's own strict ESM parser refuses.
const identifier = (name) =>
  `${name
    .replace(/\.schema\.json$/u, "")
    .split(/[^A-Za-z0-9]+/u)
    .filter(Boolean)
    .map((part, index) => (index === 0 ? part : part[0].toUpperCase() + part.slice(1)))
    .join("")}Schema`;

const lines = [
  "// GENERATED by scripts/sync-schemas.mjs from agentpkg/src/agentpkg/schemas (D-025).",
  "// Do not edit: run `npm run sync-schemas` after a schema change in agentpkg.",
  "",
  ...names.map((name) => `import ${identifier(name)} from "./${name}" with { type: "json" };`),
  "",
  "/** Every agentpkg schema, by the name `validate_document` uses (`manifest`, `policy`, ...). */",
  "export const SCHEMAS: Readonly<Record<string, unknown>> = Object.freeze({",
  ...names.map((name) => `  "${name.replace(/\.schema\.json$/u, "")}": ${identifier(name)},`),
  "});",
  "",
  "/** The schema file names in sorted order, for the equality test. */",
  "export const SCHEMA_FILES: readonly string[] = Object.freeze([",
  ...names.map((name) => `  "${name}",`),
  "]);",
  "",
];
writeFileSync(join(target, "index.ts"), lines.join("\n"));

// -- extension schemas (D-040) -----------------------------------------------------------
const extensionSource = resolve(project, "..", "spec", "extensions");
const extensionTarget = join(target, "extensions");
mkdirSync(extensionTarget, { recursive: true });
const extensionNames = readdirSync(extensionSource)
  .filter((name) => name.endsWith(".schema.json"))
  .sort();
for (const name of extensionNames) {
  writeFileSync(join(extensionTarget, name), readFileSync(join(extensionSource, name)));
}
writeFileSync(
  join(extensionTarget, "index.ts"),
  [
    "// GENERATED by scripts/sync-schemas.mjs from spec/extensions (D-040).",
    "// Do not edit: run `npm run sync-schemas` after a change to an extension schema.",
    "",
    ...extensionNames.map((name) => `import ${identifier(name)} from "./${name}" with { type: "json" };`),
    "",
    "/** Every noncritical-extension schema, by its file stem (`profiles-v0`, ...). */",
    "export const EXTENSION_SCHEMAS: Readonly<Record<string, unknown>> = Object.freeze({",
    ...extensionNames.map((name) => `  "${name.replace(/\.schema\.json$/u, "")}": ${identifier(name)},`),
    "});",
    "",
    "/** The extension schema file names in sorted order, for the equality test. */",
    "export const EXTENSION_SCHEMA_FILES: readonly string[] = Object.freeze([",
    ...extensionNames.map((name) => `  "${name}",`),
    "]);",
    "",
  ].join("\n"),
);
// -- memory.v0 contracts (T19, D-210, M-67): the schemas, the taxonomy and the patches ---------
const memorySource = resolve(project, "..", "spec", "memory-v0");
const memoryTarget = join(target, "memory");
mkdirSync(memoryTarget, { recursive: true });
const memoryNames = readdirSync(memorySource)
  .filter((name) => name.endsWith(".json"))
  .sort();
for (const name of memoryNames) {
  writeFileSync(join(memoryTarget, name), readFileSync(join(memorySource, name)));
}
const memoryIdentifier = (name) =>
  `${name
    .replace(/\.json$/u, "")
    .split(/[^A-Za-z0-9]+/u)
    .filter(Boolean)
    .map((part, index) => (index === 0 ? part : part[0].toUpperCase() + part.slice(1)))
    .join("")}Json`;
writeFileSync(
  join(memoryTarget, "index.ts"),
  [
    "// GENERATED by scripts/sync-schemas.mjs from spec/memory-v0 (T19, D-210).",
    "// Do not edit: run `npm run sync-schemas` after a change to a memory.v0 contract.",
    "",
    ...memoryNames.map((name) => `import ${memoryIdentifier(name)} from "./${name}" with { type: "json" };`),
    "",
    "/** Every memory.v0 contract, by its file stem (`memory-record.schema`, `taxonomy`, `policy.schema.patch`, ...). */",
    "export const MEMORY_CONTRACTS: Readonly<Record<string, unknown>> = Object.freeze({",
    ...memoryNames.map((name) => `  "${name.replace(/\.json$/u, "")}": ${memoryIdentifier(name)},`),
    "});",
    "",
    "/** The memory.v0 contract file names in sorted order, for the equality test. */",
    "export const MEMORY_CONTRACT_FILES: readonly string[] = Object.freeze([",
    ...memoryNames.map((name) => `  "${name}",`),
    "]);",
    "",
  ].join("\n"),
);
// -- conversation.v0 contracts (T24, D-260, D-263): the decision and transcript contracts -------
const conversationSource = resolve(project, "..", "spec", "conversation-v0");
const conversationTarget = join(target, "conversation");
mkdirSync(conversationTarget, { recursive: true });
const conversationNames = readdirSync(conversationSource)
  .filter((name) => name.endsWith(".json"))
  .sort();
for (const name of conversationNames) {
  writeFileSync(join(conversationTarget, name), readFileSync(join(conversationSource, name)));
}
writeFileSync(
  join(conversationTarget, "index.ts"),
  [
    "// GENERATED by scripts/sync-schemas.mjs from spec/conversation-v0 (T24, D-260).",
    "// Do not edit: run `npm run sync-schemas` after a change to a conversation.v0 contract.",
    "",
    ...conversationNames.map((name) => `import ${memoryIdentifier(name)} from "./${name}" with { type: "json" };`),
    "",
    "/** Every conversation.v0 contract, by its file stem (`consent-decision.schema`, `transcript.schema`, ...). */",
    "export const CONVERSATION_CONTRACTS: Readonly<Record<string, unknown>> = Object.freeze({",
    ...conversationNames.map((name) => `  "${name.replace(/\.json$/u, "")}": ${memoryIdentifier(name)},`),
    "});",
    "",
    "/** The conversation.v0 contract file names in sorted order, for the equality test. */",
    "export const CONVERSATION_CONTRACT_FILES: readonly string[] = Object.freeze([",
    ...conversationNames.map((name) => `  "${name}",`),
    "]);",
    "",
  ].join("\n"),
);
console.log(JSON.stringify({ synced: names.length, extensions: extensionNames.length, memory: memoryNames.length, conversation: conversationNames.length, target }));
