"""WebAir's human pages as its origin renders them, for offline discovery tests.

The Agent Browser's website discovery is tested without a network: a fixture stands in
for `https://webair.example` and serves these pages. Capturing them here, rather than
copying them by hand, keeps that fixture honest: `python -m publisher check` fails when
the origin's HTML, including its `rel="agent-package"` link, changes without a refresh.
"""

from __future__ import annotations

from fastapi.testclient import TestClient

from origin.agent_package import MEDIA_TYPE, PACKAGE_PATH
from origin.app import create_app

# The offline fixtures' stand-in origin: a reserved, never-resolving name (RFC 2606). The pages
# do not depend on it (their package link is relative); the public deployment's hostname is
# the package's declared host, in `contract.py`.
FIXTURE_HOST = "webair.example"

# The home page and a page deeper in the site; both advertise the same package.
PAGES = ("/", "/flight/WA101-20261009?passengers=1")


def capture_site() -> dict:
    with TestClient(create_app(), base_url=f"https://{FIXTURE_HOST}") as client:
        pages = []
        for path in PAGES:
            response = client.get(path)
            pages.append(
                {
                    "path": path,
                    "status": response.status_code,
                    "content_type": response.headers["content-type"],
                    "html": response.text,
                }
            )
    return {
        "profile": "webair-site-capture-v0",
        "note": "WebAir's own HTML pages as its origin renders them, served by offline "
        "discovery fixtures in place of the fictional https://webair.example. Generated by "
        "demo/webair/publisher; nothing in it is a real airline's.",
        "origin": f"https://{FIXTURE_HOST}",
        "agent_package": {"path": PACKAGE_PATH, "media_type": MEDIA_TYPE},
        "pages": pages,
    }
