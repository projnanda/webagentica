"""Refresh or check the generated parts of the WebAir package and its example tasks.

    cd demo/webair
    .venv/bin/python -m publisher sync    # rewrite the generated files from the origin
    .venv/bin/python -m publisher check   # exit 1 if any of them differs from the origin now,
                                          # or if the package's profiles break their rules

Generated: `agents/webair/schemas/api/*.json` (WebAir's published API contract),
`agents/webair/schemas/host/*.json` (the demo host's resource type schemas, which the
package must declare exactly), `agents/webair/fixtures/workflow.json` (the package's
recorded fixture: the fixture conversation and the search scenarios, no personal data), the
example transcripts `examples/webair-0.8.0-*.json`,
`examples/webair-0.8.0-conversations.json` (every scenario's turns, grants, picks and
expectations), `examples/webair-capability-scenarios.json` (the host-owned capability demo as
0.5.0 tasks for the OpenClaw host: grants, picks, model scripts and WebAir's answers),
`examples/webair-site.json` (the origin's own HTML pages, which offline website-discovery
fixtures serve) and `demo/webair/host-bindings.json` (the demo host's operator bindings of
the four WebAir tools to the public origin). Everything else in `agents/webair/` (manifest,
graph, policy, tool declarations, skills, package-authored schemas) is written by hand, and
the contract tests check it against the origin. The manifest's profiles
(`org.webagents:profiles-v0`) are hand-written too; `check` also validates them against
their schema and rules (`profiles.py`).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from .capabilities import capability_document
from .contract import PACKAGE_SOURCE, REPO_ROOT, contract_files
from .fixture import FIXTURE_PATH, record_fixture, source_files
from .host import host_schema_files
from .host_bindings import HOST_BINDINGS, host_bindings_document
from .profiles import source_profile_problems
from .scenarios import conversation_scenario, conversation_scenarios, scenario, scenarios
from .site import capture_site

EXAMPLES = REPO_ROOT / "examples"


def example_files(current: dict[str, bytes]) -> dict[Path, dict]:
    """The example transcripts for the README commands, every conversation scenario with what
    it must yield, and the frozen 0.5.0 capability document.

    `webair-input.json`, `webair-booking-input.json`, `webair-purchase-input.json` and
    `webair-scenarios.json` are 0.7.0's one-shot tasks and scenarios; they are no longer
    generated and stay as the documents of the shipped 0.3.0 to 0.7.0 archives (the
    conformance suite and the contract-overhead benchmark read them).
    """
    return {
        EXAMPLES / "webair-0.8.0-transcript.json": scenario("fixture").transcript(),
        EXAMPLES / "webair-0.8.0-book-transcript.json": conversation_scenario(
            "purchase"
        ).transcript(),
        EXAMPLES / "webair-capability-scenarios.json": capability_document(),
        EXAMPLES / "webair-0.8.0-conversations.json": {
            "profile": "webair-demo-conversations-v0",
            "package_id": "org.webagents.webair",
            "package_version": json.loads(current["MANIFEST.agent"])["version"],
            "note": "The conversations of the package fixture (searches only, so the signed "
            "fixture holds no personal data) and of the host-owned capability demo (the "
            "person's permission decisions and host-resource picks per conversation; the "
            "resources are the demo host's, never the package's), each turn with its message, "
            "the consent decisions the transcript supplies and what the turn must yield. "
            "Generated by demo/webair/publisher.",
            "fixture": [_conversation_record(s) for s in scenarios()],
            "capability": [_conversation_record(s) for s in conversation_scenarios()],
        },
        EXAMPLES / "webair-site.json": capture_site(),
    }


def _conversation_record(s) -> dict:
    return {
        "id": s.id,
        "summary": s.summary,
        "decisions": s.decisions,
        "selections": s.selections,
        "end": s.end,
        "turns": [
            {"message": t.input, "consents": t.consents, "expect": t.expect} for t in s.turns
        ],
    }


def generated(files: dict[str, bytes] | None = None) -> dict[Path, dict]:
    """Every generated file's document now, from the package source (or the given files)."""
    contract = {**contract_files(), **host_schema_files()}
    # Record the fixture against the schemas the origin and the host publish now.
    current = {
        **(source_files() if files is None else files),
        **{path: json.dumps(doc).encode() for path, doc in contract.items()},
    }
    documents = {PACKAGE_SOURCE / path: doc for path, doc in contract.items()}
    documents[PACKAGE_SOURCE / FIXTURE_PATH] = record_fixture(current)
    current[FIXTURE_PATH] = json.dumps(documents[PACKAGE_SOURCE / FIXTURE_PATH]).encode()
    documents.update(example_files(current))
    # The demo host's operator configuration for the four WebAir tools (not package content).
    documents[HOST_BINDINGS] = host_bindings_document()
    return documents


def render(document: dict) -> str:
    return json.dumps(document, indent=2, ensure_ascii=False) + "\n"


def drift(files: dict[str, bytes] | None = None) -> list[str]:
    stale = []
    for path, document in generated(files).items():
        if not path.is_file() or json.loads(path.read_text()) != document:
            stale.append(path.relative_to(REPO_ROOT).as_posix())
    return stale


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m publisher", description=__doc__.split("\n")[0])
    parser.add_argument("command", choices=["sync", "check"])
    args = parser.parse_args(argv)
    if args.command == "check":
        files = source_files()
        stale = drift(files)
        profiles = source_profile_problems(files)
        print(json.dumps({"stale": stale, "profile_problems": profiles}, indent=2))
        return 1 if stale or profiles else 0
    for path, document in generated().items():
        path.write_text(render(document))
        print(f"wrote {path.relative_to(REPO_ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
